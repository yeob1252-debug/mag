import { readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const icons = require('lucide-react');
const root = new URL('../', import.meta.url);
const original = execFileSync('git', ['show', '18a2b0ff07f911696a239a4ae6907425f887bed2:index.html'], {cwd:root,encoding:'utf8'});
const head = original.match(/<head>[\s\S]*?<\/head>/)?.[0];
const forms = [...original.matchAll(/<form class="v6-owner-form"[\s\S]*?<\/form>/g)];
if (!head || forms.length !== 1) throw new Error('Baseline document contract mismatch');
const replaceMeta = (source, attribute, name, content) => {
  const pattern = new RegExp(`<meta\\s+${attribute}="${name}"\\s+content="[^"]*"\\s*\\/?>`);
  if (!pattern.test(source)) throw new Error(`Missing ${attribute}=${name} in baseline head`);
  return source.replace(pattern, `<meta ${attribute}="${name}" content="${content}">`);
};
const shareTitle = '맛집감별사 | 휴대폰 하나로 시작하는 맛집 콘텐츠';
const shareDescription = '대구 원데이 실습부터 음식점 맞춤 크리에이터 연결까지';
const shareImage = 'https://www.matgamsa.com/assets/og/matgamsa-share-20260906-v4.png';
const shareAlt = '맛집감별사 - 휴대폰 하나로 시작하는 맛집 콘텐츠와 음식점 크리에이터 연결';
let refreshedHead = head.replace(/<title>[\s\S]*?<\/title>/, `<title>${shareTitle}</title>`);
refreshedHead = replaceMeta(refreshedHead, 'name', 'description', `${shareDescription}, 휴대폰으로 시작하는 맛집 콘텐츠의 다음 단계를 안내합니다.`);
refreshedHead = replaceMeta(refreshedHead, 'property', 'og:title', shareTitle);
refreshedHead = replaceMeta(refreshedHead, 'property', 'og:description', shareDescription);
refreshedHead = replaceMeta(refreshedHead, 'property', 'og:image', shareImage);
refreshedHead = replaceMeta(refreshedHead, 'property', 'og:image:secure_url', shareImage);
refreshedHead = replaceMeta(refreshedHead, 'property', 'og:image:alt', shareAlt);
refreshedHead = replaceMeta(refreshedHead, 'name', 'twitter:title', shareTitle);
refreshedHead = replaceMeta(refreshedHead, 'name', 'twitter:description', shareDescription);
refreshedHead = replaceMeta(refreshedHead, 'name', 'twitter:image', shareImage);
refreshedHead = refreshedHead.replace(/(<meta property="og:image:secure_url"[^>]*>)/, '$1\n  <meta property="og:image:type" content="image/png">');
refreshedHead = refreshedHead.replace(/(<meta name="twitter:image"[^>]*>)/, '$1\n  <meta name="twitter:image:alt" content="' + shareAlt + '">');
refreshedHead = refreshedHead.replace('</head>', '  <link rel="stylesheet" href="css/motion-v6-polish.css?v=20260907-v1">\n</head>');
let html = await readFile(new URL('./home-motion.template.html', import.meta.url), 'utf8');
html = html.replace('{{HEAD}}', refreshedHead.replace('css/hero-v6-preview.css?v=20260902-v8', 'css/motion-refresh.css?v=20260907-v6')).replace('{{OWNER_FORM}}', forms[0][0]);
html = html.replace(/\{\{icon:(\w+)\}\}/g, (_, name) => {
  name = ({Ellipsis:'MoreHorizontal',House:'Home',CirclePlus:'PlusCircle'})[name] || name;
  if (!icons[name]) throw new Error('Unknown Lucide icon: ' + name);
  return renderToStaticMarkup(React.createElement(icons[name], {size:20,strokeWidth:1.8,'aria-hidden':true,focusable:false}));
});
if (html.includes('{{')) throw new Error('Unresolved template token');
await writeFile(new URL('index.html', root), html);
console.log('Built homepage; baseline owner form preserved byte-for-byte.');
